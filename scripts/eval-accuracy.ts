/**
 * Accuracy of the evidence review and of "reach out now", measured against hand labels (tests/evals/labels.json).
 * Read-only against whatever DATABASE_URL points at. No Gemini and no search credits are used: it reads the verdicts the
 * pipeline has already stored.   npm run eval:accuracy   → writes docs/ACCURACY.md
 *
 * Honest limits, repeated in the report: n is small, one person labelled it, the labels come from the stored excerpt, and the
 * rules were designed after looking at this same sample, so the "reach out now" numbers are in-sample. The review verdicts
 * (acting / sector) were produced by Gemini without ever seeing the labels, so those agreement numbers are not tuned.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { getDb } from "../src/lib/db";

interface Label { url: string; firm_name: string; headline: string; acting: boolean; sector: string; new_capital: boolean; note: string; action_before: string | null; score_before: number | null }
const labels = (JSON.parse(readFileSync("tests/evals/labels.json", "utf8")) as { signals: Label[] }).signals;
const ORDER = ["logistics", "b2b_software", "seed_generalist", "adjacent", "unrelated"];
const db = getDb();
const stored = (await db.query<{ url: string; firm_name: string; sector_match: string | null; firm_acting: boolean | null; verification_status: string; action: string | null; score: number | null }>(
  `select s.url, i.firm_name, s.sector_match, s.firm_acting, s.verification_status, i.recommended_action as action, i.follow_up_score as score
     from signals s join investors i on i.id = s.investor_id where s.url = any($1::text[])`, [labels.map((l) => l.url)],
)).rows;
await db.close();
const by = new Map(stored.map((s) => [s.url, s]));
const rows = labels.flatMap((l) => { const s = by.get(l.url); return s && s.sector_match ? [{ l, s }] : []; });

// ── 1. is the firm really acting? ──
const flaggedNotActing = rows.filter((r) => r.s.firm_acting === false);
const truePositive = flaggedNotActing.filter((r) => !r.l.acting).length;
const mislabelled = rows.filter((r) => !r.l.acting).length;
const falseFlags = flaggedNotActing.filter((r) => r.l.acting);

// ── 2. topic agreement ──
const exact = rows.filter((r) => r.s.sector_match === r.l.sector).length;
const matrix = ORDER.map((a) => ORDER.map((b) => rows.filter((r) => r.l.sector === a && r.s.sector_match === b).length));
const lenient = rows.filter((r) => ORDER.indexOf(r.s.sector_match!) < ORDER.indexOf(r.l.sector)).length;
const strict = rows.filter((r) => ORDER.indexOf(r.s.sector_match!) > ORDER.indexOf(r.l.sector)).length;
const logisticsModel = rows.filter((r) => r.s.sector_match === "logistics");
const logisticsPrecision = logisticsModel.filter((r) => r.l.sector === "logistics").length;
const logisticsLabel = rows.filter((r) => r.l.sector === "logistics");
const logisticsRecall = logisticsLabel.filter((r) => r.s.sector_match === "logistics").length;

// ── 3. "reach out now": would a founder agree it deserves a cold approach? ──
// Worth it = the lead signal is about logistics, or announces new capital for seed/B2B investing.
const worth = (l: Label) => l.sector === "logistics" || (l.new_capital && (l.sector === "b2b_software" || l.sector === "seed_generalist"));
const before = labels.filter((l) => l.action_before === "reach_out_now");
const after = rows.filter((r) => r.s.action === "reach_out_now");
const worthy = labels.filter(worth);
const pct = (a: number, b: number) => (b ? `${Math.round((a / b) * 100)}%` : "n/a");

const md = `# Accuracy against hand labels

Generated by \`npm run eval:accuracy\` on ${new Date().toISOString().slice(0, 10)}. It reads the verdicts the pipeline has already stored (no Gemini calls, no search credits).

## How to read this honestly

- **n = ${labels.length}.** One lead signal for each of the ${labels.length} highest-scoring investors at the time, labelled by the developer from the stored evidence excerpt and source (\`tests/evals/labels.json\`), *not* from model output.
- **Two different claims.** (a) The Gemini review verdicts (firm acting? topic?) were produced without ever seeing these labels, so section 1 and 2 are a fair agreement measure. (b) The gating rules were written after looking at this same sample, so section 3 is **in-sample**: it shows the rules do what they were designed to do, not that they generalise.
- Small samples hide rare failures. Treat percentages as indications, not guarantees.

## 1. Is the investor really the one acting? (second-pass review)

| | Count |
|---|---|
| Signals reviewed | ${rows.length} |
| Labelled as a wrong-firm / not-acting signal | ${mislabelled} |
| ...of which the review caught | **${truePositive}** of ${mislabelled} |
| Review flagged as not acting | ${flaggedNotActing.length} |
| ...of which the label disagrees (false flags) | ${falseFlags.length}${falseFlags.length ? ` (${falseFlags.map((r) => `${r.l.firm_name}: ${r.l.note}`).join("; ")})` : ""} |

The case it exists for: ${labels.filter((l) => !l.acting).map((l) => `**${l.firm_name}**, ${l.note}`).join("; ")}. The first-pass checks (name match, verbatim quote) let it through; the second pass caught it.

## 2. How close is the topic to logistics? (sector_match)

Exact agreement: **${exact} of ${rows.length}** (${pct(exact, rows.length)}).
Where it disagrees, the model is more generous than the label in ${lenient} cases and stricter in ${strict}.

| label \\ model | ${ORDER.join(" | ")} |
|---|${ORDER.map(() => "---").join("|")}|
${ORDER.map((a, i) => `| **${a}** | ${matrix[i]!.join(" | ")} |`).join("\n")}

**The class that matters most is "logistics"**, because it alone can earn "reach out now" without extra conditions: precision ${logisticsPrecision} of ${logisticsModel.length}, recall ${logisticsRecall} of ${logisticsLabel.length}. The disagreements are mostly between the neighbouring middle classes (adjacent / general seed / B2B software), which the scoring treats alike (relevance capped at 45 or 62).

## 3. "Reach out now": does the shortlist deserve a cold email? (in-sample)

A lead signal "deserves" a cold approach if it is about logistics, or announces new capital for seed / B2B investing.

| | Before the review and gates | After (live data) |
|---|---|---|
| Investors recommended "reach out now" (of the ${labels.length} labelled) | ${before.length} | ${after.length} |
| ...whose lead signal deserves it | ${before.filter(worth).length} of ${before.length} (${pct(before.filter(worth).length, before.length)}) | ${after.filter((r) => worth(r.l)).length} of ${after.length} (${pct(after.filter((r) => worth(r.l)).length, after.length)}) |
| Deserving investors that got "reach out now" (recall) | ${before.filter(worth).length} of ${worthy.length} | ${after.filter((r) => worth(r.l)).length} of ${worthy.length} |

Before: ${before.map((l) => `${l.firm_name} (${l.sector}${worth(l) ? "" : ", NOT worth it"})`).join(", ")}.
After: ${after.map((r) => `${r.l.firm_name} (${r.l.sector})`).join(", ") || "none"}.

The system is now deliberately **conservative**: precision went up and recall went down, because a deserving signal that fails a gate (for example, a press article from an unrecognised site, or a score just under the threshold) is shown as "prepare targeted outreach" with the reason, rather than as "reach out now". The what-if page (\`/simulate\`) lets the founder loosen those rules and see who moves.
`;
writeFileSync("docs/ACCURACY.md", md);
console.log(md);
