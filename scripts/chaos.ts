/**
 * Fault-injection report. Runs the real refresh pipeline over a seeded world while search, page fetches, Gemini and the
 * database fail at random, then checks the invariants and that a fault-free recovery run converges to the fault-free answer.
 * Runs entirely in-process (no network, no credentials, no credits).   npm run chaos   → writes docs/CHAOS.md
 */
import { writeFileSync } from "node:fs";
import { baseline, runChaos, type ChaosReport } from "../tests/helpers/chaos";

const N = 24;
const SEEDS = [1, 2, 3, 4, 5, 6];
const RATES = [0.15, 0.3, 0.6];

const expected = await baseline(N);
const reports: ChaosReport[] = [];
for (const rate of RATES) for (const seed of SEEDS) {
  const r = await runChaos({ seed, rate, investors: N }, expected);
  reports.push(r);
  console.log(`seed ${seed} rate ${rate}: ${r.invariants.filter((i) => i.ok).length}/${r.invariants.length} invariants, injected ${Object.values(r.injected).reduce((a, b) => a + b, 0)} faults, chaos run ${r.chaos_run.status} (${r.chaos_run.done} done, ${r.chaos_run.failed} failed), recovery ${r.recovery_status}`);
}

const kinds = [...new Set(reports.flatMap((r) => Object.keys(r.injected)))].sort();
const total = (k: string) => reports.reduce((a, r) => a + (r.injected[k] ?? 0), 0);
const allInv = reports.flatMap((r) => r.invariants);
const names = [...new Set(allInv.map((i) => i.name))];
const md = `# Fault-injection report

Generated by \`npm run chaos\` on ${new Date().toISOString().slice(0, 10)}. Everything runs in-process on a migrated Postgres (PGlite) with **no network, no credentials and no search credits**.

**What it does.** A seeded world of ${N} investors (every third has a real, verifiable logistics article) is refreshed through the *real* pipeline while every dependency fails at random:
search (429 / 5xx / timeout / malformed), page fetches (5xx / timeout), Gemini (outage, 429, garbage JSON) and the database (a transaction that dies *after* its writes, so only rollback keeps the data consistent).
Part-way through, one invocation is "killed" (items stuck as running, stale heartbeat) and the run must resume. Then faults are switched off and a normal run must converge to **exactly** the result of a fault-free run.

## Result

${reports.length} scenarios (${SEEDS.length} seeds × ${RATES.length} fault rates: ${RATES.map((r) => `${r * 100}%`).join(", ")}), ${total("search:rate_limited") + total("search:http_5xx") + total("search:timeout") + total("search:malformed") + total("page:unreadable") + total("gemini:unavailable") + total("gemini:rate_limited") + total("gemini:garbage") + total("db:fail_after_writes")} injected faults in total.

| Invariant | Scenarios passing |
|---|---|
${names.map((n) => `| ${n} | ${allInv.filter((i) => i.name === n && i.ok).length} / ${allInv.filter((i) => i.name === n).length} |`).join("\n")}

## Injected faults (all scenarios)

| Fault | Count |
|---|---|
${kinds.map((k) => `| ${k.replace(":", " · ")} | ${total(k)} |`).join("\n")}

## Per scenario

| Seed | Fault rate | Faults | Chaos run | Items done / failed | Attempts | Crash resumed | Recovery run | Invariants |
|---|---|---|---|---|---|---|---|---|
${reports.map((r) => `| ${r.seed} | ${Math.round(r.rate * 100)}% | ${Object.values(r.injected).reduce((a, b) => a + b, 0)} | ${r.chaos_run.status} | ${r.chaos_run.done} / ${r.chaos_run.failed} | ${r.chaos_run.attempts} | ${r.chaos_run.resumed ? "yes" : "n/a"} | ${r.recovery_status} | ${r.invariants.filter((i) => i.ok).length}/${r.invariants.length} |`).join("\n")}

## Bugs this found (and fixed)

1. **A transient page failure became a permanent rejection.** A candidate whose page timed out and that had no date in the search snippet was stored as a final "rejected" and never looked at again. It is now "needs review: page unavailable" and is retried on the next run.
2. **A transient page failure became a permanent confidence penalty.** Evidence judged from the search snippet because the page timed out kept its capped confidence for ever, so recovery could not restore the score a fault-free run gives. Such evidence is now marked *provisional* and is re-fetched and re-judged on the next run. (A robots.txt block or a 404 is not retried: that would waste calls every run.)
3. **A review that failed once stayed failed.** Evidence whose second-pass review hit a Gemini outage was never reviewed again. Un-reviewed in-window evidence is now retried on later refreshes, and the investor is re-scored.

Each is also pinned as a plain regression test in \`tests/chaos.test.ts\`.
`;
writeFileSync("docs/CHAOS.md", md);
const bad = allInv.filter((i) => !i.ok);
console.log(`\nwrote docs/CHAOS.md; ${bad.length} failed invariant checks`);
if (bad.length) { console.error(JSON.stringify(bad.slice(0, 5), null, 1)); process.exit(1); }
